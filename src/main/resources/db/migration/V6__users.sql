CREATE TABLE users (
                       id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       username      VARCHAR(50)              NOT NULL UNIQUE,
                       password_hash VARCHAR(100)             NOT NULL,
                       created_at    TIMESTAMP WITH TIME ZONE NOT NULL
);


ALTER TABLE accounts   ADD COLUMN owner_id BIGINT REFERENCES users (id);
ALTER TABLE categories ADD COLUMN owner_id BIGINT REFERENCES users (id);
ALTER TABLE budgets    ADD COLUMN owner_id BIGINT REFERENCES users (id);


CREATE INDEX idx_accounts_owner_id   ON accounts (owner_id);
CREATE INDEX idx_categories_owner_id ON categories (owner_id);
CREATE INDEX idx_budgets_owner_id    ON budgets (owner_id);


ALTER TABLE categories DROP CONSTRAINT categories_name_key;
CREATE UNIQUE INDEX uq_categories_owner_name  ON categories (owner_id, name) WHERE owner_id IS NOT NULL;
CREATE UNIQUE INDEX uq_categories_global_name ON categories (name)           WHERE owner_id IS NULL;


ALTER TABLE budgets DROP CONSTRAINT uq_budgets_category_month;
ALTER TABLE budgets ADD CONSTRAINT uq_budgets_owner_category_month UNIQUE (owner_id, category_id, month);